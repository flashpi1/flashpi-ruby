# frozen_string_literal: true

# Keeps the README examples checked: every ```ruby block of README.md and README.en.md becomes a
# file in test/examples/readme/, which Steep type-checks against the gem's signatures (the bodies
# against the API's types too), RuboCop lints and the tests compile on every supported Ruby.
# Those files are never run.
#
#   ruby scripts/readme.rb generate  rewrite test/examples/readme/ from the READMEs
#   ruby scripts/readme.rb check     fail when it is out of date (CI and the tests run it)
#
# Names a block uses without defining them, such as the `flashpi` client of "Getting started" or
# the `request` of a Rails controller, are declared in test/examples/sig/: any other unknown name
# is a Steep error.

# The commands of this script.
module Readme
  ROOT = File.expand_path("..", __dir__)
  EXAMPLES = File.join("test", "examples", "readme")
  READMES = { "es" => "README.md", "en" => "README.en.md" }.freeze
  FENCE = /\A```\s*([\w+-]*)/
  HEADING = /\A\#{1,6}\s+(.+?)\s*\z/

  # A ```ruby block of a README.
  Block = Struct.new(:readme, :line, :section, :code, keyword_init: true)

  # A README block that cannot become a checked file.
  class ExampleError < StandardError; end

  module_function

  # The ```ruby blocks of a Markdown text, in order, each with the heading above it.
  def ruby_blocks(readme, text)
    found = []
    section = ""
    lines = text.lines.map(&:chomp)
    index = 0
    while index < lines.size
      line = lines[index]
      fence = FENCE.match(line)
      if fence.nil?
        heading = HEADING.match(line)
        section = heading[1] if heading
        index += 1
        next
      end
      start = index
      index += 1
      index += 1 while index < lines.size && !lines[index].start_with?("```")
      raise ExampleError, "#{readme}:#{start + 1}: a code block is not closed" if index >= lines.size

      if %w[ruby rb].include?(fence[1])
        found << Block.new(readme:, line: start + 1, section:, code: "#{lines[(start + 1)...index].join("\n")}\n")
      end
      index += 1
    end
    found
  end

  # Each example file (relative path) and its text.
  def examples
    READMES.flat_map do |prefix, readme|
      blocks = ruby_blocks(readme, File.read(File.join(ROOT, readme), encoding: "UTF-8"))
      blocks.each_with_index.map do |block, number|
        name = File.join(EXAMPLES, format("%<prefix>s_%<number>02d.rb", prefix:, number: number + 1))
        [name, render(block)]
      end
    end.to_h
  end

  def render(block)
    <<~RUBY
      # frozen_string_literal: true

      # GENERATED by scripts/readme.rb from #{block.readme} (the block at line #{block.line}, "#{block.section}").
      # Do not edit by hand: change the README, then run `ruby scripts/readme.rb generate`.

      #{block.code.chomp}
    RUBY
  end

  def current
    Dir.glob(File.join(ROOT, EXAMPLES, "*.rb")).to_h do |path|
      [path.delete_prefix("#{ROOT}/"), File.read(path, encoding: "UTF-8")]
    end
  end

  def main(argv)
    mode = argv.first || "generate"
    unless %w[generate check].include?(mode) && argv.size <= 1
      warn "Usage: ruby scripts/readme.rb generate|check"
      return 2
    end
    wanted = examples
    if mode == "check"
      return 0 if wanted == current

      warn "#{EXAMPLES} does not match the READMEs. Run: ruby scripts/readme.rb generate"
      return 1
    end
    (current.keys - wanted.keys).each { |name| File.delete(File.join(ROOT, name)) }
    wanted.each { |name, text| File.write(File.join(ROOT, name), text) }
    puts "Wrote #{wanted.size} examples to #{EXAMPLES}"
    0
  end
end

exit(Readme.main(ARGV)) if $PROGRAM_NAME == __FILE__
